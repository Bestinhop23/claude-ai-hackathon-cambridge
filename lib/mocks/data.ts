const today = new Date("2026-03-07T10:00:00.000Z");

function buildSeries(ticker: string, base: number, drift: number, volatility: number): PriceSeries {
  const points = Array.from({ length: 30 }, (_, index) => {
    const date = new Date(today);
    date.setDate(today.getDate() - (29 - index));
    const step = base + index * drift + Math.sin(index / 2) * volatility;
    const benchmark = 100 + index * 0.45 + Math.cos(index / 3) * 1.2;
    return {
      date: date.toISOString().slice(0, 10),
      close: Number(step.toFixed(2)),
      benchmarkClose: Number(benchmark.toFixed(2)),
      volume: Math.round(35_000_000 + index * 420_000 + ((index % 4) - 1.5) * 1_250_000),
    };
  });

  return {
    ticker,
    benchmarkTicker: "SPY",
    points,
  };
}

